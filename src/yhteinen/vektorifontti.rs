//! Viivoista koostuva otsikkofontti. Merkit on piirretty ruudukkoon 4x6, ääkkösten pisteet
//! ovat sen yläpuolella. Vain versaalit: leipäteksti käyttää bittikarttafonttia.

type Kuvio = &'static [&'static [(i8, i8)]];

pub const LEVEYS: i32 = 4;
pub const KORKEUS: i32 = 6;

const O: &[(i8, i8)] = &[
    (1, 0),
    (3, 0),
    (4, 1),
    (4, 5),
    (3, 6),
    (1, 6),
    (0, 5),
    (0, 1),
    (1, 0),
];
const A: &[(i8, i8)] = &[(0, 6), (0, 2), (2, 0), (4, 2), (4, 6)];
const A_VIIVA: &[(i8, i8)] = &[(0, 4), (4, 4)];
const P: &[(i8, i8)] = &[(0, 6), (0, 0), (3, 0), (4, 1), (4, 2), (3, 3), (0, 3)];
const PISTE_V: &[(i8, i8)] = &[(1, -2), (1, -1)];
const PISTE_O: &[(i8, i8)] = &[(3, -2), (3, -1)];

pub fn kuvio(merkki: char) -> Kuvio {
    match merkki {
        'A' => &[A, A_VIIVA],
        'B' => &[
            &[
                (0, 0),
                (3, 0),
                (4, 1),
                (4, 2),
                (3, 3),
                (4, 4),
                (4, 5),
                (3, 6),
                (0, 6),
                (0, 0),
            ],
            &[(0, 3), (3, 3)],
        ],
        'C' => &[&[
            (4, 1),
            (3, 0),
            (1, 0),
            (0, 1),
            (0, 5),
            (1, 6),
            (3, 6),
            (4, 5),
        ]],
        'D' => &[&[(0, 0), (3, 0), (4, 1), (4, 5), (3, 6), (0, 6), (0, 0)]],
        'E' => &[&[(4, 0), (0, 0), (0, 6), (4, 6)], &[(0, 3), (3, 3)]],
        'F' => &[&[(4, 0), (0, 0), (0, 6)], &[(0, 3), (3, 3)]],
        'G' => &[&[
            (4, 1),
            (3, 0),
            (1, 0),
            (0, 1),
            (0, 5),
            (1, 6),
            (3, 6),
            (4, 5),
            (4, 3),
            (2, 3),
        ]],
        'H' => &[&[(0, 0), (0, 6)], &[(4, 0), (4, 6)], &[(0, 3), (4, 3)]],
        'I' => &[&[(1, 0), (3, 0)], &[(2, 0), (2, 6)], &[(1, 6), (3, 6)]],
        'J' => &[&[(4, 0), (4, 5), (3, 6), (1, 6), (0, 5)]],
        'K' => &[&[(0, 0), (0, 6)], &[(4, 0), (0, 3), (4, 6)]],
        'L' => &[&[(0, 0), (0, 6), (4, 6)]],
        'M' => &[&[(0, 6), (0, 0), (2, 2), (4, 0), (4, 6)]],
        'N' => &[&[(0, 6), (0, 0), (4, 6), (4, 0)]],
        'O' => &[O],
        'P' => &[P],
        'Q' => &[O, &[(2, 4), (4, 6)]],
        'R' => &[P, &[(2, 3), (4, 6)]],
        'S' => &[&[
            (4, 1),
            (3, 0),
            (1, 0),
            (0, 1),
            (0, 2),
            (1, 3),
            (3, 3),
            (4, 4),
            (4, 5),
            (3, 6),
            (1, 6),
            (0, 5),
        ]],
        'T' => &[&[(0, 0), (4, 0)], &[(2, 0), (2, 6)]],
        'U' => &[&[(0, 0), (0, 5), (1, 6), (3, 6), (4, 5), (4, 0)]],
        'V' => &[&[(0, 0), (2, 6), (4, 0)]],
        'W' => &[&[(0, 0), (1, 6), (2, 3), (3, 6), (4, 0)]],
        'X' => &[&[(0, 0), (4, 6)], &[(4, 0), (0, 6)]],
        'Y' => &[&[(0, 0), (2, 3), (4, 0)], &[(2, 3), (2, 6)]],
        'Z' => &[&[(0, 0), (4, 0), (0, 6), (4, 6)]],
        'Ä' => &[A, A_VIIVA, PISTE_V, PISTE_O],
        'Ö' => &[O, PISTE_V, PISTE_O],
        '0' => &[O, &[(1, 5), (3, 1)]],
        '1' => &[&[(1, 1), (2, 0), (2, 6)], &[(1, 6), (3, 6)]],
        '2' => &[&[(0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (0, 6), (4, 6)]],
        '3' => &[
            &[(0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (3, 3), (1, 3)],
            &[(3, 3), (4, 4), (4, 5), (3, 6), (1, 6), (0, 5)],
        ],
        '4' => &[&[(3, 6), (3, 0), (0, 4), (4, 4)]],
        '5' => &[&[
            (4, 0),
            (0, 0),
            (0, 3),
            (3, 3),
            (4, 4),
            (4, 5),
            (3, 6),
            (1, 6),
            (0, 5),
        ]],
        '6' => &[&[
            (3, 0),
            (1, 0),
            (0, 1),
            (0, 5),
            (1, 6),
            (3, 6),
            (4, 5),
            (4, 4),
            (3, 3),
            (0, 3),
        ]],
        '7' => &[&[(0, 0), (4, 0), (1, 6)]],
        '8' => &[&[
            (1, 3),
            (0, 2),
            (0, 1),
            (1, 0),
            (3, 0),
            (4, 1),
            (4, 2),
            (3, 3),
            (1, 3),
            (0, 4),
            (0, 5),
            (1, 6),
            (3, 6),
            (4, 5),
            (4, 4),
            (3, 3),
        ]],
        '9' => &[&[
            (1, 6),
            (3, 6),
            (4, 5),
            (4, 1),
            (3, 0),
            (1, 0),
            (0, 1),
            (0, 2),
            (1, 3),
            (4, 3),
        ]],
        '!' => &[&[(2, 0), (2, 4)], &[(2, 5), (2, 6)]],
        '*' => &[&[(2, 1), (2, 5)], &[(0, 2), (4, 4)], &[(4, 2), (0, 4)]],
        '-' => &[&[(1, 3), (3, 3)]],
        _ => &[],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn otsikoiden_merkit_on_piirretty_ruudukkoon() {
        let tekstit = "PISTEET PARAS SUURIN SIIRROT SAIT PÄÄTTYI PELIKONE LAIVANUPOTUS VASTUSTAJAN OMA VOITIT HÄVISIT HIHIHIHIII PELIN ÖÄ * ! 0123456789";
        for merkki in tekstit.chars().filter(|&m| m != ' ') {
            let kuvio = kuvio(merkki);
            assert!(!kuvio.is_empty(), "{merkki}");
            for &(x, y) in kuvio.iter().flat_map(|osa| osa.iter()) {
                assert!((0..=LEVEYS as i8).contains(&x), "{merkki}");
                assert!((-2..=KORKEUS as i8).contains(&y), "{merkki}");
            }
        }
    }
}
